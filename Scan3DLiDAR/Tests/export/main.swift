import Foundation
var count = 0
func check(_ ok: Bool, _ message: String) {
    guard ok else { fatalError("TEST FEJLEDE: \(message)") }
    count += 1
}
let cloud = PointCollector(resolution:0.02,maxPoints:3)
let zero = CloudVertex(x:0,y:0,z:0)
cloud.add(zero,target:nil)
check(cloud.count == 1,"første punkt")
cloud.add(CloudVertex(x:0.006,y:0.004,z:0.003),target:nil)
check(cloud.count == 1,"voxel dublet")
cloud.add(CloudVertex(x:0.2,y:0,z:0),target:zero,radius:0.1)
check(cloud.count == 1,"udenfor mål")
cloud.add(CloudVertex(x:1,y:0,z:0),target:nil)
cloud.add(CloudVertex(x:2,y:0,z:0),target:nil)
cloud.add(CloudVertex(x:3,y:0,z:0),target:nil)
check(cloud.count == 3,"maksimumgrænse")
let invalid = CloudVertex(x:Float.nan,y:0,z:0)
check(!invalid.finite,"NaN-forkastelse")
let ply = String(decoding: GeometryExport.ply(points:cloud.snapshot()),as:UTF8.self)
check(ply.contains("element vertex 3"),"PLY-antal")
check(ply.hasPrefix("ply\nformat ascii 1.0\n"),"PLY-format")
check(ply.contains("property float z\nend_header"),"PLY-header")
let obj = String(decoding:GeometryExport.obj(vertices:[zero, CloudVertex(x:1,y:0,z:0),CloudVertex(x:0,y:1,z:0)],triangles:[(0,1,2),(-1,1,2)]),as:UTF8.self)
check(obj.contains("f 1 2 3"),"OBJ 1-baseret")
check(!obj.contains("f 0"),"OBJ udelader ugyldig flade")
// Index remapping must never connect a face to the wrong vertex after filtering.
let vx = CloudVertex(x:1,y:0,z:0)
let vy = CloudVertex(x:0,y:1,z:0)
let collinear = CloudVertex(x:2,y:0,z:0)
let samePosition = CloudVertex(x:0,y:0,z:0)
let infinite = CloudVertex(x:0,y:.infinity,z:0)
let clean = GeometryExport.validatedOBJ(
    vertices:[zero,invalid,vx,vy,collinear,samePosition,infinite],
    triangles:[(0,2,3),(3,2,0),(2,3,0),(0,0,3),(0,2,4),(0,2,5),(1,2,3),(0,2,6),(0,2,7),(-1,2,3),(0,3,2)])
let cleanText = String(decoding:clean.data,as:UTF8.self)
let cleanLines = cleanText.split(separator:"\n")
check(cleanLines.filter { $0.hasPrefix("v ") }.count == 5,"nonfinite vertices excluded")
check(cleanLines.filter { $0.hasPrefix("f ") }.map(String.init) == ["f 1 2 3"],"remapped indices preserve first valid winding")
check(clean.triangleCount == 1 && clean.discardedTriangleCount == 10,"reported face counts match output")
check(!cleanText.lowercased().contains("nan") && !cleanText.lowercased().contains("inf"),"no invalid numeric tokens")
let empty = GeometryExport.validatedOBJ(vertices:[invalid,infinite],triangles:[(0,1,0)])
check(empty.triangleCount == 0 && empty.discardedTriangleCount == 1,"no face when all vertices are invalid")
check(!String(decoding:empty.data,as:UTF8.self).split(separator:"\n").contains { $0.hasPrefix("v ") || $0.hasPrefix("f ") },"empty geometry does not fabricate vertices")
let tiny = GeometryExport.validatedOBJ(vertices:[zero,CloudVertex(x:1e-20,y:0,z:0),CloudVertex(x:0,y:1e-20,z:0)],triangles:[(0,1,2)])
check(tiny.triangleCount == 1,"very small nonzero-area triangle preserved")
let second = GeometryExport.validatedOBJ(vertices:[zero,vx,vy,collinear],triangles:[(0,1,2),(1,3,2)])
check(second.triangleCount == 2,"adjacent distinct faces retained")
cloud.clear()
check(cloud.count == 0,"nulstil")
print("PASS \(count)/\(count) point-cloud / PLY / OBJ")
