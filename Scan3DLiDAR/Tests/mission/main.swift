import Foundation
let target = ScanPoint(x:0,y:0,z:0)
var assertions = 0
func check(_ ok: Bool, _ label: String) { if !ok { fatalError("FAIL \(label)") }; assertions += 1 }
check(MissionGeometry.slot(camera:.init(x:0,y:0,z:1),target:target) == ScanSlot(ring:1,sector:0),"front")
check(MissionGeometry.slot(camera:.init(x:1,y:0,z:0),target:target) == ScanSlot(ring:1,sector:3),"right")
check(MissionGeometry.slot(camera:.init(x:0,y:0,z:-1),target:target) == ScanSlot(ring:1,sector:6),"rear")
check(MissionGeometry.slot(camera:.init(x:-1,y:0,z:0),target:target) == ScanSlot(ring:1,sector:9),"left")
check(MissionGeometry.slot(camera:.init(x:0,y:0.7,z:1),target:target)?.ring == 2,"high")
check(MissionGeometry.slot(camera:.init(x:0,y:-0.7,z:1),target:target)?.ring == 0,"low")
check(MissionGeometry.slot(camera:.init(x:0,y:0,z:0.1),target:target) == nil,"too close for slot")
let p=ScanPoint(x:0,y:0,z:1)
let good=MissionGeometry.evaluate(camera:p,forward:.init(x:0,y:0,z:-1),target:target,trackingGood:true,still:true)!
check(good.ready,"ready when facing target and still")
check(!MissionGeometry.evaluate(camera:p,forward:.init(x:1,y:0,z:0),target:target,trackingGood:true,still:true)!.ready,"wrong heading")
check(!MissionGeometry.evaluate(camera:p,forward:.init(x:0,y:0,z:-1),target:target,trackingGood:true,still:false)!.ready,"moving")
check(!MissionGeometry.evaluate(camera:p,forward:.init(x:0,y:0,z:-1),target:target,trackingGood:false,still:true)!.ready,"tracking lost")
check(!MissionGeometry.evaluate(camera:.init(x:0,y:0,z:3),forward:.init(x:0,y:0,z:-1),target:target,trackingGood:true,still:true)!.ready,"too far")
check(MissionGeometry.nextUncovered(after:0,covered:[1,2])?.index == 3,"next missing")
check(MissionGeometry.nextUncovered(after:35,covered:[])?.index == 0,"wrap")
check(MissionGeometry.nextUncovered(after:nil,covered:Set(0..<36)) == nil,"all covered")
// V11: New guidance selects uncovered positions and never re-offers a finished slot.
let routeCurrent = ScanSlot(ring:1, sector:0)
check(MissionRoute.nearestUncovered(from:routeCurrent,covered:[]) == routeCurrent,"current slot prioritized")
check(MissionRoute.nearestUncovered(from:routeCurrent,covered:[12])?.index == 13,"next uncovered same ring")
check(MissionRoute.nearestUncovered(from:routeCurrent,covered:Set(12..<24))?.ring != 1,"next missing ring")
check(MissionRoute.nearestUncovered(from:routeCurrent,covered:Set(0..<36)) == nil,"route complete")
check(MissionRoute.navigate(from:routeCurrent,covered:[])?.stepCount == 0,"no movement at empty slot")
check(MissionRoute.navigate(from:routeCurrent,covered:[12])?.stepCount == 1,"suggest 30 degrees")
check(MissionRoute.navigate(from:routeCurrent,covered:[12])?.message.contains("med uret") == true,"direction clockwise")
check(MissionRoute.navigate(from:ScanSlot(ring:1,sector:0),covered:Set(12..<24))?.message.contains("kameraet") == true,"height guidance")
check(MissionRoute.navigate(from:routeCurrent,covered:Set(0..<36)) == nil,"all covered no route")
print("PASS \(assertions)/\(assertions) - native orbital mission geometry + route v11")

// v12 explicit retake: only the selected covered position, never some other slot.
check(MissionRetake.select(slot: 12, covered: [12,13]) == 12, "retake covered")
check(MissionRetake.select(slot: 14, covered: [12,13]) == nil, "retake missing denied")
check(MissionRetake.select(slot: -1, covered: [12]) == nil, "negative slot denied")
check(MissionRetake.select(slot: 36, covered: [12]) == nil, "overflow slot denied")
check(MissionRetake.canCapture(slot: 12, covered: [12], retake: 12, cameraReady: true), "retake selected allowed")
check(!MissionRetake.canCapture(slot: 12, covered: [12], retake: nil, cameraReady: true), "duplicate blocked")
check(!MissionRetake.canCapture(slot: 12, covered: [12], retake: 13, cameraReady: true), "wrong slot blocked")
check(!MissionRetake.canCapture(slot: 12, covered: [12], retake: 12, cameraReady: false), "unstable retake blocked")
check(MissionRetake.canCapture(slot: 14, covered: [12], retake: nil, cameraReady: true), "new slot allowed")
check(!MissionRetake.canCapture(slot: 14, covered: [12], retake: 12, cameraReady: true), "unrelated new photo blocked")
check(MissionRoute.navigateTo(from: ScanSlot(ring:1,sector:1), target:ScanSlot(ring:1,sector:0)).message.contains("mod uret"),"retake navigate backward")
check(MissionRoute.navigateTo(from: ScanSlot(ring:1,sector:1), target:ScanSlot(ring:2,sector:1)).message.contains("Hæv"),"retake navigate higher")
print("PASS V12 - explicit retake policy and route")
